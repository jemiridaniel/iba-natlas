# Clinician danger-sign question ids are the rule codes themselves.
CLINICIAN_DANGER = {code.value: plain for plain, code in DANGER_QUESTIONS.items()}


def _options(table: dict[str, dict[Lang, str]], lang: Lang) -> list[dict[str, str]]:
    return [{"value": value, "text": text[lang]} for value, text in table.items()]


def questions(mode: Mode, lang: Lang) -> list[dict]:
    """The question list for a mode, worded in `lang`."""
    if mode == "self_report":
        out: list[dict] = [
            {"id": "fever", "type": "yes_no", "text": _PLAIN["fever"][lang]},
            {
                "id": "fever_days",
                "type": "number",
                "unit": "days",
                "ask_if": "fever",
                "text": _PLAIN["fever_days"][lang],
            },
        ]
        out += [{"id": q, "type": "yes_no", "text": _PLAIN[q][lang]} for q in DANGER_QUESTIONS]
        return out

    out = [
        {"id": "fever_days", "type": "number", "unit": "days", "text": _PLAIN["fever_days"][lang]},
        {
            "id": "temperature_c",
            "type": "number",
            "unit": "°C",
            "optional": True,
            "text": _CLINICIAN["temperature_c"][lang],
        },
        {"id": "state", "type": "text", "optional": True, "text": _CLINICIAN["state"][lang]},
        {
            "id": "rdt_result",
            "type": "choice",
            "text": _CLINICIAN["rdt_result"][lang],
            "options": _options(_RDT_OPTIONS, lang),
        },
        {
            "id": "no_treatment_response",
            "type": "yes_no",
            "text": _CLINICIAN["no_treatment_response"][lang],
        },
        {
            "id": "lassa_symptoms",
            "type": "multi_choice",
            "text": _CLINICIAN["lassa_symptoms"][lang],
            "options": _options(LASSA_SYMPTOM_OPTIONS, lang),
        },
    ]
    # Health workers get the clinical label (English, the language of the guidelines)
    # beside the plain question they can read to the patient.
    out += [
        {
            "id": code.value,
            "type": "yes_no",
            "label": DANGER_SIGN_LABELS[code],
            "text": _PLAIN[CLINICIAN_DANGER[code.value]][lang],
        }
        for code in DangerSignCode
    ]
    return out
